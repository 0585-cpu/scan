fn main() {
    ensure_placeholder_icon();
    tauri_build::build();
}

fn ensure_placeholder_icon() {
    let icon_path = std::path::Path::new("icons").join("icon.ico");
    if icon_path
        .metadata()
        .is_ok_and(|metadata| metadata.len() == PLACEHOLDER_ICO.len() as u64)
    {
        return;
    }
    std::fs::create_dir_all("icons").expect("failed to create Tauri icons directory");
    std::fs::write(icon_path, PLACEHOLDER_ICO).expect("failed to write placeholder Tauri icon");
}

